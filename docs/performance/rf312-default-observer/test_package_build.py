from pathlib import Path
import tempfile
import unittest

import package_build as build


class BuildInputs(unittest.TestCase):
    def setUp(self):
        temporary=tempfile.TemporaryDirectory();self.addCleanup(temporary.cleanup)
        self.root=Path(temporary.name).resolve();self.source=self.root/'source';self.source.write_bytes(b'current bytes')
        self.target=self.root/'nested/target';self.expected=build.entry(self.source)
    def test_install_keeps_source_bytes_and_cannot_replace_conflicting_output(self):
        build.install(self.source,self.target,self.expected)
        self.assertEqual(self.target.read_bytes(),b'current bytes')
        build.install(self.source,self.target,self.expected)
        self.target.write_bytes(b'other bytes')
        with self.assertRaisesRegex(ValueError,'Conflicting'):build.install(self.source,self.target,self.expected)
        self.assertEqual(self.target.read_bytes(),b'other bytes')
    def test_changed_source_is_refused_before_destination(self):
        self.source.write_bytes(b'changed')
        with self.assertRaisesRegex(ValueError,'input changed'):build.install(self.source,self.target,self.expected)
        self.assertFalse(self.target.exists())
    def test_existing_output_refuses_without_loading_a_library(self):
        marker=self.root/'marker';marker.write_bytes(b'keep')
        with self.assertRaisesRegex(ValueError,'New output'):build.configure({},self.root)
        self.assertEqual(marker.read_bytes(),b'keep')
    def test_invalid_schema_refuses_before_output_mutation(self):
        config={n:None for n in build.FIELDS};config['schemaVersion']=True
        target=self.root/'new'
        with self.assertRaisesRegex(ValueError,'Complete source-bound'):build.configure(config,target)
        self.assertFalse(target.exists())


class PackageIdentity(unittest.TestCase):
    def setUp(self):
        self.text="package: name='com.solosoul.app' versionCode='2013002' versionName='2.13.2'\nminSdkVersion:'28'\ntargetSdkVersion:'36'\nlaunchable-activity: name='com.solosoul.app.MainActivity'\nnative-code: 'x86_64'\n"
        self.version=dict(versionName='2.13.2',versionCode=2013002)
    def test_actual_current_badging_fields_pass(self):build.verify_badging(self.text,self.version)
    def test_debug_foreign_abi_and_wrong_current_version_refuse(self):
        for text in (self.text+'application-debuggable\n',self.text.replace("native-code: 'x86_64'","native-code: 'x86_64' 'arm64-v8a'"),self.text.replace("versionCode='2013002'","versionCode='1'")):
            with self.subTest(text=text),self.assertRaises(ValueError):build.verify_badging(text,self.version)


class TrackedVersionProperties(unittest.TestCase):
    def setUp(self):
        temporary=tempfile.TemporaryDirectory();self.addCleanup(temporary.cleanup)
        self.path=Path(temporary.name).resolve()/'tauri.properties'
        self.key='tauri/src-tauri/gen/android/app/tauri.properties'
        self.version=dict(versionName='2.13.2',versionCode=2013002,
            properties='tauri.android.versionCode=2013002\ntauri.android.versionName=2.13.2\n')
        self.body=b'// THIS IS AN AUTOGENERATED FILE.\r\ntauri.android.versionName=2.13.2\r\ntauri.android.versionCode=2013002\r\n'
    def test_current_bound_version_file_preserves_every_source_byte(self):
        self.path.write_bytes(self.body);expected=build.entry(self.path)
        result=build.stage_version_file(self.path,self.key,{self.key:expected},self.version)
        self.assertTrue(result['trackedSourcePreserved'])
        self.assertEqual({k:result[k] for k in ('bytes','sha256')},expected)
        self.assertEqual(self.path.read_bytes(),self.body)
    def test_foreign_changed_or_ambiguous_tracked_version_refuses_without_rewrite(self):
        for body in (self.body.replace(b'2013002',b'1'),self.body+b'tauri.android.versionCode=2013002\n',
                     self.body+b'unbound.property=1\n'):
            with self.subTest(body=body):
                self.path.write_bytes(body)
                with self.assertRaises(ValueError):build.stage_version_file(self.path,self.key,{self.key:build.entry(self.path)},self.version)
                self.assertEqual(self.path.read_bytes(),body)
        self.path.write_bytes(self.body);expected=build.entry(self.path);self.path.write_bytes(b'changed')
        with self.assertRaisesRegex(ValueError,'file changed'):build.stage_version_file(self.path,self.key,{self.key:expected},self.version)
        self.assertEqual(self.path.read_bytes(),b'changed')
    def test_only_untracked_absent_version_file_can_be_generated(self):
        result=build.stage_version_file(self.path,self.key,{},self.version)
        self.assertFalse(result['trackedSourcePreserved'])
        self.assertEqual(self.path.read_bytes(),self.version['properties'].encode('ascii'))
        with self.assertRaisesRegex(ValueError,'Unbound'):build.stage_version_file(self.path,self.key,{},self.version)


if __name__=='__main__':unittest.main()
